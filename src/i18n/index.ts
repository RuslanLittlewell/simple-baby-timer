export type LanguageCode = (typeof LANGUAGES)[number]['code'];

export const DEFAULT_LANGUAGE: LanguageCode = 'en';

// Ukrainian used to be stored under its ISO 639-1 code; installations that
// picked it before the rename would otherwise silently drop to English.
const LEGACY_CODES: Record<string, LanguageCode> = { uk: 'ua' };

export function normalizeLanguage(code: unknown): LanguageCode {
  if (typeof code === 'string' && code in LEGACY_CODES) return LEGACY_CODES[code];
  return LANGUAGES.some((l) => l.code === code) ? (code as LanguageCode) : DEFAULT_LANGUAGE;
}

